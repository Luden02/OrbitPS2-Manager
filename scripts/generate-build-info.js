/**
 * Generates angular/src/app/shared/build-info.ts with version, build number,
 * build date, and an optional release channel. Run before any Angular build.
 *
 * ORBIT_CHANNEL=nightly stamps the Nightly channel without changing the
 * version in package.json. The GitHub pre-release is titled "Nightly".
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const CHANNELS = new Set(['alpha', 'beta', 'rc', 'nightly', 'indev']);

function normalizeChannel(channel) {
  if (typeof channel !== 'string') return null;
  const value = channel.trim().toLowerCase();
  return CHANNELS.has(value) ? value : null;
}

function renderBuildInfo({ version, buildNumber, buildDate, author, channel }) {
  const safeChannel = normalizeChannel(channel);
  const channelLiteral = safeChannel ? `'${safeChannel}'` : 'null';
  return `// AUTO-GENERATED by scripts/generate-build-info.js — do not edit.
export const BuildInfo = {
  version: '${version}',
  buildNumber: '${buildNumber}',
  buildDate: '${buildDate}',
  author: '${author}',
  channel: ${channelLiteral},
} as const;
`;
}

function main() {
  const pkg = require('../package.json');

  let buildNumber = 'dev';
  try {
    buildNumber = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    buildNumber = `local-${Date.now().toString(36)}`;
  }

  const buildDate = new Date().toISOString();
  const channel = normalizeChannel(process.env.ORBIT_CHANNEL);
  const out = renderBuildInfo({
    version: pkg.version,
    buildNumber,
    buildDate,
    author: pkg.author,
    channel,
  });

  const target = path.join(__dirname, '..', 'angular', 'src', 'app', 'shared', 'build-info.ts');
  fs.writeFileSync(target, out);
  console.log(`[build-info] ${pkg.version} · ${buildNumber} · ${buildDate}${channel ? ` · ${channel}` : ''}`);
}

if (require.main === module) {
  main();
}

module.exports = { renderBuildInfo, normalizeChannel };
